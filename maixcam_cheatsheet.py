#  08. ЦВЕТ В LAB И ПОДБОР ПОРОГОВ  (самый важный раздел для соревнований!)
# ══════════════════════════════════════════════════════════════════════════════
#
#   Все цветовые алгоритмы (find_blobs, get_regression и др.) работают
#   с порогами в цветовом пространстве LAB:
#
#       [L_MIN, L_MAX, A_MIN, A_MAX, B_MIN, B_MAX]
#        L — яркость (0..100)
#        A — зелёно-красная ось (-128..127)
#        B — сине-жёлтая ось   (-128..127)
#
#   Стартовые пороги из официальной документации:
#
#   RED    = [0, 80,  40,   80,  10,  80]     # красный
#   GREEN  = [0, 80, -120, -10,   0,  30]     # зелёный
#   BLUE   = [0, 80,  30,  100, -120, -60]    # синий
#   # Чёрная линия на светлом полу (КАЛИБРОВАТЬ!):
#   BLACK  = [0, 30, -128, 127, -128, 127]
#   # Белая линия:
#   WHITE  = [70, 100, -128, 127, -128, 127]
#
#   КАК ПОДБИРАТЬ ПОРОГИ ПОД СВОЮ ПЛОЩАДКУ:
#     1. В MaixVision запустите камеру, выделите мышью область нужного цвета —
#        внизу появится гистограмма каналов. Пороги читаются прямо с неё.
#     2. Либо штатное приложение «Find Blobs» на устройстве: ткните в объект —
#        приложение покажет его LAB-значения и само выставит пороги.
#     3. Освещение на площадке отличается от домашнего — всегда перепроверяйте
#        пороги на месте и имейте запасной комплект.
#
# ══════════════════════════════════════════════════════════════════════════════
#  09. ПОИСК ЦВЕТНЫХ ПЯТЕН — img.find_blobs
# ══════════════════════════════════════════════════════════════════════════════
#
#   from maix import image, camera, display
#
#   cam  = camera.Camera(320, 240)
#   disp = display.Display()
#
#   thresholds = [[0, 80, 40, 80, 10, 80]]       # красный
#
#   while 1:
#       img = cam.read()
#       blobs = img.find_blobs(thresholds, pixels_threshold=500)
#       for blob in blobs:
#           # blob[0]=x, blob[1]=y, blob[2]=ширина, blob[3]=высота
#           img.draw_rect(blob[0], blob[1], blob[2], blob[3], image.COLOR_GREEN)
#       disp.show(img)
#
#   # Основные параметры:
#   #   thresholds       — список порогов; можно НЕСКОЛЬКО цветов сразу:
#   #                      [[...красный...], [...зелёный...]]
#   #   invert=True      — инвертировать пороги
#   #   roi=[x,y,w,h]    — искать только в части кадра (ускоряет!)
#   #   area_threshold   — отбросить пятна меньше по площади (по умолч. 10)
#   #   pixels_threshold — отбросить пятна с малым числом «своих» пикселей
#
#   # Типичная логика «возьми самый большой объект»:
#   #   if blobs:
#   #       best = max(blobs, key=lambda b: b[2] * b[3])
#   #       cx = best[0] + best[2] // 2        # центр объекта по X
#   #       err = cx - img.width() // 2        # отклонение от центра кадра
#
