# ══════════════════════════════════════════════════════════════════════════════
#
#   Поддерживаются из коробки: YOLOv5, YOLOv8, YOLO11, YOLO26
#   (v8 -> MaixPy>=4.3.0, YOLO11 -> >=4.7.0, YOLO26 -> >=4.12.5).
#
#   from maix import camera, display, image, nn, app
#
#   detector = nn.YOLO11(model="/root/models/yolo11n.mud", dual_buff=True)
#   # другие варианты:
#   # detector = nn.YOLOv5(model="/root/models/yolov5s.mud",  dual_buff=True)
#   # detector = nn.YOLOv8(model="/root/models/yolov8n.mud",  dual_buff=True)
#   # detector = nn.YOLO26(model="/root/models/yolo26n.mud",  dual_buff=True)
#
#   cam  = camera.Camera(detector.input_width(),
#                        detector.input_height(),
#                        detector.input_format())
#   disp = display.Display()
#
#   while not app.need_exit():
#       img = cam.read()
#       objs = detector.detect(img, conf_th=0.5, iou_th=0.45)
#       for obj in objs:
#           img.draw_rect(obj.x, obj.y, obj.w, obj.h, color=image.COLOR_RED)
#           msg = f'{detector.labels[obj.class_id]}: {obj.score:.2f}'
#           img.draw_string(obj.x, obj.y, msg, color=image.COLOR_RED)
#       disp.show(img)
#
#   # Ключевые моменты:
#   #   • Модель = файл .mud в /root/models/. Проверка:  ls /root/models/
#   #   • Если файлов нет — скачать из зоопарка моделей:
#   #       YOLOv5: https://maixhub.com/model/zoo/365
#   #       YOLOv8: https://maixhub.com/model/zoo/400
#   #       YOLO11: https://maixhub.com/model/zoo/453
#   #     и закинуть в /root/models/ через файловый менеджер или WinSCP.
#   #   • Вход модели по умолчанию 320x224 (MaixCAM) — быстро.
#   #     Нужно точнее — берите модель большего входа, но будет медленнее.
#   #   • Ориентиры скорости на MaixCAM: YOLO11n ~95 fps @320x320,
#   #     ~23 fps @640x640.
#   #   • Готовые модели знают 80 классов COCO (человек, мяч, бутылка,
